namespace LowlandTech.Components.Components.DataGrid;

/// <summary>
/// Specifies the sort direction for a DataGrid column.
/// </summary>
public enum SortDirection
{
    /// <summary>
    /// No sorting applied.
    /// </summary>
    None,

    /// <summary>
    /// Sort in ascending order.
    /// </summary>
    Ascending,

    /// <summary>
    /// Sort in descending order.
    /// </summary>
    Descending
}
