namespace LowlandTech.Components.Components.DataGrid;

/// <summary>
/// Specifies where the pager should be displayed in a DataGrid.
/// </summary>
public enum PagerPosition
{
    /// <summary>
    /// Pager appears below the grid.
    /// </summary>
    Bottom,

    /// <summary>
    /// Pager appears above the grid.
    /// </summary>
    Top,

    /// <summary>
    /// Pagers appear both above and below the grid.
    /// </summary>
    TopAndBottom
}
